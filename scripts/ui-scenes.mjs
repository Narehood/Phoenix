// A fixed, fresh review dataset. Not served by Phoenix or bundled into the app.
export async function captureUI({ send, sessionId, evaluate, wait, click, capture }) {
  const viewport = (width, height) => send("Emulation.setDeviceMetricsOverride", { width, height, deviceScaleFactor: 1, mobile: width < 720 }, sessionId);
  const settle = () => evaluate("new Promise(done => requestAnimationFrame(() => requestAnimationFrame(done)))");
  const shot = async (name) => {
    await settle();
    if (!await evaluate("document.documentElement.scrollWidth <= innerWidth")) throw Error(`Horizontal document overflow in ${name}`);
    await capture(name);
  };
  const navigate = async (name) => {
    await evaluate("if (innerWidth <= 720) document.querySelector('.mobile-navigation').open = true");
    await click(name);
  };
  const top = () => evaluate("window.scrollTo(0, 0)");
  const section = async (selector) => {
    await evaluate(`document.querySelector(${JSON.stringify(selector)})?.scrollIntoView({block:'start'})`);
    await settle();
  };
  await evaluate("window.fixture.visualScene(); document.documentElement.dataset.mode = 'light'");
  await wait("document.body.innerText.includes('edge-01')");
  await shot("fleet-desktop");
  await click("edge-01");
  await wait("document.body.innerText.includes('systemd-journald')");
  await shot("host-desktop");
  await evaluate("document.querySelector('.host-actions').open = true");
  await shot("host-management-desktop");
  await evaluate("document.querySelector('.host-actions').open = false");
  await evaluate("window.fixture.populateHistory()");
  await wait("!!document.querySelector('.history svg')");
  await shot("host-history-desktop");
  await evaluate("document.querySelector('.history-data').open = true");
  await section(".cpu-history");
  await shot("host-history-data-desktop");
  await evaluate("window.fixture.samples = []");
  await wait("!document.querySelector('.history svg')");
  await top();
  await evaluate("(() => { const h = window.fixture.hosts[0]; window.fixture.freshHost = structuredClone(h); h.freshness = 'stale'; h.connectivity = 'offline'; h.resourceHealth = 'unknown'; h.lastContact -= 900000; h.latest.measuredAt -= 900000; h.latest.collectedAt -= 900000; })()");
  await wait("!!document.querySelector('.reading-snapshot') && document.querySelectorAll('.retained-label').length === 4");
  await top();
  await shot("host-retained-desktop");
  await evaluate("[...document.querySelectorAll('h2')].find(h => h.textContent === 'systemd services').closest('section').scrollIntoView({block:'start'})");
  await shot("host-retained-services-desktop");
  await evaluate("Object.assign(window.fixture.hosts[0], window.fixture.freshHost); delete window.fixture.freshHost");
  await wait("!document.querySelector('.reading-snapshot')");
  await navigate("Projects");
  await wait("document.body.innerText.includes('Website')");
  await top();
  await shot("projects-desktop");
  await click("Website");
  await wait("document.querySelector('h1')?.textContent.includes('Website') && document.body.innerText.includes('example/website')");
  await shot("repository-desktop");
  await section(".github .section");
  await shot("repository-checks-desktop");
  await evaluate("document.querySelector('.project-settings > summary').click()");
  await section(".project-settings");
  await shot("project-settings-desktop");
  await evaluate("(() => { const input = document.querySelector('input[name=editName]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'Website updated'); input.dispatchEvent(new Event('input', {bubbles:true})); window.fixture.recent = false; })()");
  await evaluate("document.querySelector('form[aria-label=\"Project details\"]').requestSubmit()");
  await wait("document.querySelector('.project-edit-feedback [role=alert]')?.innerText.includes('Verify identity')");
  await shot("project-verification-feedback-desktop");
  await evaluate("(() => { window.fixture.recent = true; const input = document.querySelector('input[name=editName]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'Website'); input.dispatchEvent(new Event('input', {bubbles:true})); document.querySelector('.project-edit-feedback [aria-label=\"Dismiss error\"]').click(); })()");
  await navigate("Access & accounts");
  await wait("document.querySelector('select[name=user] option[value=operator-fixture]')");
  await top();
  await shot("access-desktop");
  await evaluate(`(() => { const select = document.querySelector('select[name=user]'); Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(select, 'operator-fixture'); select.dispatchEvent(new Event('change', {bubbles:true})); })()`);
  await wait(`!!document.querySelector('[data-grant="host:viewer-host:host.read"]') && !!document.querySelector('[data-grant="project:website:project.read"]')`);
  await section(".grant-editor");
  await shot("access-grants-desktop");
  await click("Create account");
  await wait("document.querySelector('.account-create').open");
  await section(".account-create");
  await shot("account-create-desktop");
  await navigate("Fleet overview");
  await top();
  await evaluate("window.fixture.failSources.add('/api/audit'); window.fixture.hosts[0].latest.cpuPercent = 37");
  await wait("[...document.querySelectorAll('[role=alert]')].some(a => a.innerText.includes('Activity unavailable')) && document.querySelector('.fleet-table').innerText.includes('37.0%')");
  await shot("fleet-audit-unavailable-desktop");
  await evaluate("window.fixture.failSources.clear(); window.fixture.hosts[0].latest.cpuPercent = 12");
  await wait("!document.querySelector('[role=alert]') && document.querySelector('.fleet-table').innerText.includes('12.0%')");
  await viewport(1440, 390);
  await evaluate("[...document.querySelectorAll('.sidebar button')].find(b => b.textContent === 'Sign out').focus()");
  await shot("navigation-short-desktop");
  await viewport(1440, 1000);
  await evaluate("document.querySelector('.sidebar').scrollTop = 0");
  await viewport(390, 844);
  await shot("fleet-mobile");
  await evaluate("document.querySelector('.mobile-navigation').open = true");
  await shot("navigation-mobile");
  await viewport(390, 390);
  await evaluate("document.querySelector('.mobile-menu-body').scrollTop = 10000");
  await shot("navigation-short-mobile");
  await viewport(390, 844);
  await evaluate("document.querySelector('.mobile-navigation').open = false");
  await evaluate("window.fixture.hosts[1].resourceHealth = 'warning'; window.fixture.hosts[1].latest.cpuPercent = 96");
  await wait("document.querySelector('.attention-filter')?.textContent.includes('(2)')");
  await click("Agent / readings issues");
  await wait("document.querySelectorAll('.fleet-table tbody tr').length === 2");
  await top();
  await shot("fleet-attention-mobile");
  await evaluate("window.fixture.hosts[1].resourceHealth = 'normal'; window.fixture.hosts[1].latest.cpuPercent = 12");
  await click("Show all hosts");
  await wait("document.querySelectorAll('.fleet-table tbody tr').length === 3");
  await click("edge-01");
  await wait("document.querySelector('h1')?.textContent === 'edge-01'");
  await top();
  await shot("host-mobile");
  await evaluate("window.fixture.populateHistory()");
  await wait("!!document.querySelector('.history svg')");
  await evaluate("document.querySelector('.history-data').open = true");
  await section(".cpu-history");
  await shot("host-history-mobile");
  await navigate("Projects");
  await wait("document.body.innerText.includes('Website')");
  await top();
  await shot("projects-mobile");
  await click("Website");
  await wait("document.querySelector('h1')?.textContent.includes('Website') && document.body.innerText.includes('example/website')");
  await shot("repository-mobile");
  await viewport(1440, 1000);
  await top();
  await evaluate("document.documentElement.dataset.mode = 'dark'");
  await shot("repository-dark");
  await navigate("Fleet overview");
  await top();
  await shot("fleet-dark");
  await evaluate("document.documentElement.dataset.mode = 'light'; window.fixture.projects = {}");
  await navigate("Projects");
  await wait("document.body.innerText.includes('No projects yet')");
  await top();
  await shot("empty-projects-desktop");
  await click("Verify identity");
  await wait("document.querySelector('dialog[open]')");
  await shot("verification-dialog");
  await evaluate("window.fixture.authFailure = 503; document.querySelector('dialog input[name=password]').value = 'temporary fixture password'; document.querySelector('dialog input[name=code]').value = '123456'; document.querySelector('dialog form').requestSubmit()");
  await wait("document.querySelector('dialog [role=alert]')?.textContent.includes('Fixture verification unavailable')");
  await shot("verification-error");
  await click("×");
  await click("Sign out");
  await wait("document.querySelector('input[name=code]')");
  await shot("sign-in-desktop");
}
